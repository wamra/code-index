#!/usr/bin/env bash
# Regenerate THIRD_PARTY_NOTICES.md from the Go modules that end up in the
# binary (the dependencies of ./cmd/... on darwin, linux and windows) and their
# license files in the module cache. Needs the modules downloaded
# (go mod download). Usage: scripts/gen-notices.sh [OUTFILE]
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="${1:-$ROOT/THIRD_PARTY_NOTICES.md}"
cd "$ROOT"

mods="$(for os in darwin linux windows; do
  GOOS=$os go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}}|{{.Version}}|{{with .Replace}}{{.Path}}|{{.Version}}{{else}}|{{end}}|{{.Dir}}{{end}}{{end}}' ./cmd/...
done | LC_ALL=C sort -u)"

# files DIR PATTERN...: base names of the regular files in DIR whose name matches
# one of the find -iname patterns, sorted.
files() {
  local d="$1"; shift
  local args=() p
  for p in "$@"; do args+=(-o -iname "$p"); done
  find "$d" -maxdepth 1 -type f \( "${args[@]:1}" \) -exec basename {} \; | LC_ALL=C sort
}

# spdx FILE: a licence identifier recognised from the text, else UNKNOWN.
spdx() {
  if grep -q 'Apache License' "$1" && grep -q 'Version 2.0' "$1"; then echo "Apache-2.0"
  elif grep -q 'Permission is hereby granted, free of charge' "$1"; then echo "MIT"
  elif grep -q 'Redistribution and use in source and binary forms' "$1"; then
    if grep -q 'Neither the name' "$1"; then echo "BSD-3-Clause"; else echo "BSD-2-Clause"; fi
  else echo "UNKNOWN"; fi
}

{
cat <<'HDR'
# Third-party notices

code-index is released under the license in `LICENSE`. The binary contains the
Go modules and other components listed below. This file is generated by
`scripts/gen-notices.sh`; do not edit the module sections by hand.

## Components that are not plain Go modules

- **SQLite** (public domain): the database engine, compiled to WebAssembly and
  embedded in the binary through the SQLite module below.
- **ncruces/go-sqlite3 and its WebAssembly build of SQLite** (MIT, copyright
  Nuno Cruces): the Go driver and the `sqlite3.wasm` it embeds. This repository
  does not use the upstream module as published: `go.mod` has
  `replace github.com/ncruces/go-sqlite3 => github.com/wamra/go-sqlite3`, a
  public fork of it. The fork's license text is reproduced below under its
  module path.
- **sqlite-vec** (dual-licensed MIT or Apache-2.0, upstream
  <https://github.com/asg017/sqlite-vec>): the vector-search extension, used
  through the Go module `github.com/asg017/sqlite-vec-go-bindings`, which embeds
  a WebAssembly build of SQLite with sqlite-vec. The Go bindings module ships no
  license file in the module cache, so its entry below says UNKNOWN; the
  upstream sqlite-vec license terms are the ones named here.
- **AWS SDK for Go v2** (Apache-2.0): used for the optional Bedrock provider.
  Its `NOTICE` text is reproduced with its modules below.
- No tree-sitter or other parser grammars are part of this build.

## Go modules in the binary
HDR
printf '\nModule | Version | License\n--- | --- | ---\n'
while IFS='|' read -r path ver rpath rver dir; do
  [ -n "$path" ] || continue
  [ -d "$dir" ] || { echo "module directory missing for $path (run: go mod download)" >&2; exit 1; }
  lic="$(files "$dir" 'licen[cs]e*' 'copying*' | head -1)"
  id=UNKNOWN; [ -n "$lic" ] && id="$(spdx "$dir/$lic")"
  shown="$path"; [ -n "$rpath" ] && shown="$path (replaced by $rpath)"
  v="$ver"; [ -n "$rpath" ] && v="$rver"
  echo "$shown | $v | $id"
done <<<"$mods"

while IFS='|' read -r path ver rpath rver dir; do
  [ -n "$path" ] || continue
  v="$ver"; shown="$path"; if [ -n "$rpath" ]; then v="$rver"; shown="$path (replaced by $rpath)"; fi
  echo
  echo "## $shown $v"
  echo
  lics="$(files "$dir" 'licen[cs]e*' 'copying*')"
  if [ -z "$lics" ]; then
    echo "License: UNKNOWN (no license file in the module cache copy of this module)."
  else
    for f in $lics; do
      echo "License: $(spdx "$dir/$f") (file \`$f\`)"
      echo
      echo '```text'
      cat "$dir/$f"
      echo
      echo '```'
    done
  fi
  for f in $(files "$dir" 'notice*'); do
    echo
    echo "NOTICE (file \`$f\`):"
    echo
    echo '```text'
    cat "$dir/$f"
    echo
    echo '```'
  done
done <<<"$mods"
} > "$OUT"
echo "wrote $OUT"
